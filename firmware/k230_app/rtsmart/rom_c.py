#!/usr/bin/env python3
"""The product program as a C file for the kernel's ROMFS (DESIGN.md 5.3.7: the program inside the A/B slot, updated
and rolled back with the kernel): /app/leakcam in the root table of app_canmv/mnt.c (install.sh's ROMFS patch).
Without a program (install.sh's placeholder before the first build) the file is empty.
    rom_c.py <program or -> <out.c>
"""
import sys

prog, out = sys.argv[1], sys.argv[2]
data = b"" if prog == "-" else open(prog, "rb").read()
rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
with open(out, "w") as f:
    f.write("/* generated by firmware/k230_app/rtsmart/rom_c.py: the product program in the slot's ROMFS, /app/leakcam\n"
            " * (DESIGN.md 5.3.7); %d bytes */\n" % len(data))
    f.write("#include <rtthread.h>\n#include <dfs_romfs.h>\n\n")
    f.write("static const rt_uint8_t leakcam_prog[%d] = {\n    %s\n};\n\n" % (max(len(data), 1), ",\n    ".join(rows) or "0"))
    f.write("const struct romfs_dirent leakcam_rom_app[] = {\n"
            "    {ROMFS_DIRENT_FILE, \"leakcam\", leakcam_prog, %d},\n};\n" % len(data))
